// Local preparation only: never commits, uploads or publishes anything.
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const {version}=JSON.parse(await readFile(path.join(root,'release.json'),'utf8'));
if (!/^\d+\.\d+\.\d+$/.test(version)) throw Error('Use a semantic release version');
const check=process.argv.includes('--check');
const sources=['index.html','sw.js',...(await readdir(path.join(root,'src'))).filter(n=>n.endsWith('.js')).map(n=>'src/'+n)];
let stale=false;
for(const name of sources) {
 const file=path.join(root,name),old=await readFile(file,'utf8');
 const next=old.replace(/([?&]v=)\d+\.\d+\.\d+/g,`$1${version}`)
  .replace(/(from\s+['"]\.\/?[^'"?]+\.js)(['"])/g,`$1?v=${version}$2`);
 if(next!==old) {if(check) stale=true;else await writeFile(file,next);}
}
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const names=['index.html','styles.css','manifest.webmanifest','manifest.pl.webmanifest','icon-192.png','icon-512.png',...(await readdir(path.join(root,'src'))).filter(n=>n.endsWith('.js')).map(n=>'src/'+n)];
const assets=[];
for(const name of names) {
 const url='./'+name+((name.endsWith('.js')||name.endsWith('.css'))?`?v=${version}`:'');
 assets.push({url,sha256:hash(await readFile(path.join(root,name)))});
}
assets.unshift({url:'./',sha256:assets[0].sha256});
const id=`${version}-${hash(JSON.stringify({assets,worker:hash(await readFile(path.join(root,'sw.js')))})).slice(0,16)}`;
const output='// Generated by npm run prepare:release. Do not edit by hand.\nself.PILOT_RELEASE = '+JSON.stringify({version,id,assets},null,2)+';\n';
let current='';try{current=await readFile(path.join(root,'release-manifest.js'),'utf8');}catch{}
if(check) {if(stale||current!==output)throw Error('Release files are stale; run npm run prepare:release');console.log(`Release ${id}: hashes and versioned paths verified`);}
else {await writeFile(path.join(root,'release-manifest.js'),output);console.log(`Prepared local release ${id}`);}
